def _reduce_conflict(canon: str, top: list[dict]) -> int | None:
    """Confirm a split top-candidate set WITHOUT guessing, else None (hold).

    Ported from build._reduce_conflict; the acode-based checks are re-expressed
    against label_raw because report_lines carries no acode.
    """
    rows = top
    # narrow-prefer: drop broad '및기타/AndOther' accounts when a pure one exists
    if canon in _NARROW_PREFER:
        narrow = [r for r in rows if not _BROAD_RE.search(r.get("label_raw") or "")]
        if narrow:
            rows = narrow
    # current-strict: a current canonical must not absorb non-current (장기/비유동) rows
    if canon in _CURRENT_STRICT:
        cur = [r for r in rows if not _is_noncurrent(r)]
        if cur:
            rows = cur
    # revenue grand-total preference: a grand-total label (매출액/영업수익) outranks a
    # component label (수수료수익/이자수익/보험영업수익…) that also maps to is.revenue.
    # Fixes securities/holdings where 영업수익 total conflicts with 수수료수익 component
    # (both top-level exact). Insurers under IFRS17 have no such total (or =0) → unaffected.
    if canon == "is.revenue":
        grand = [r for r in rows
                 if _norm_label(r.get("label_raw")) in _REVENUE_TOTAL_LABELS and r["value"]]
        if grand:
            gvals = {r["value"] for r in grand}
            if len(gvals) == 1:
                return next(iter(gvals))
            rows = grand  # multiple grand totals disagree → decide among them below
    def _eps_dup(candidate_vals):
        """Near-equal same-sign values (e.g. original vs restated) -> max-abs, else None."""
        nums = [v for v in candidate_vals if v is not None]
        if len(nums) < 2:
            return None
        hi = max(nums, key=abs)
        lo = min(nums, key=abs)
        if hi == 0 or (hi > 0) != (lo > 0):
            return None
        return hi if abs(hi - lo) / abs(hi) <= _CONFLICT_EPS else None

    vals = {r["value"] for r in rows}
    if len(vals) == 1:
        return next(iter(vals))
    # EPS approx-dup FIRST: an immaterial restatement diff (original vs amended) resolves
    # to max-abs, so the shallowest-depth rule below doesn't override it on a rounding gap.
    dup = _eps_dup(vals)
    if dup is not None:
        return dup
    # shallowest-depth preference: DIRECT_MAP canonicals are statement totals, so the
    # least-nested line outranks deeper sub-items that map to the same canonical
    # (e.g. 'Ⅰ.영업수익' total vs its '보험료수익' children; or IFRS17 '보험서비스수익'
    # at 보험손익 depth-1 vs '수수료수익' at 투자손익>… depth-2). Only fires on an existing
    # conflict, so it can fill a held NULL but never regress a match.
    def _depth(r):
        p = (r.get("section_path") or "").strip()
        return 0 if not p else p.count(">") + 1
    # exclude 0-valued candidates: an IFRS17 empty top-level header (e.g. '영업수익'=0
    # above 보험손익/투자손익 sections) must not win as a shallowest "total".
    pool = [r for r in rows if r["value"] not in (0, None)]
    if not pool:
        return None
    pvals = {r["value"] for r in pool}
    if len(pvals) == 1:
        return next(iter(pvals))          # a single distinct non-zero value
    min_depth = min(_depth(r) for r in pool)
    shallow = [r for r in pool if _depth(r) == min_depth]
    svals = {r["value"] for r in shallow}
    if len(svals) == 1:
        return next(iter(svals))
    return _eps_dup(svals)  # shallowest still split → EPS among them, else hold


def _resolve(cands: dict[str, list[dict]], corp: str | None = None,
             fy: int | None = None, period: str | None = None, basis: str | None = None):
    """{canonical: [candidate]} -> (confirmed {canonical: value}, conflicts {canonical: [candidate]}).

    Ported from build._resolve. Conflicts are HELD (not filled) and returned for
    analysis (only for consumed canonicals, to avoid lineage noise).

    corp: current corp_code, needed only to gate the curated overrides
    (_REVENUE_TOTAL_OVERRIDE_CORPS / _TRADE_PAYABLES_PARENT_OVERRIDE_CORPS) below.
    fy/period: current fiscal_year/fiscal_period, needed only to gate
    _TRADE_PAYABLES_ADDITIVE_OVERRIDE (period-scoped, not corp-blanket — see its
    comment for why).
    basis: current basis (연결/별도), needed only to gate
    _TRADE_PAYABLES_STALE_SUBLINE_OVERRIDE (basis-scoped — see its comment for why).
    """
    confirmed: dict[str, int] = {}
    conflicts: dict[str, list[dict]] = {}
    trust_seqs = _trust_account_table_seqs(cands)
    degenerate_eq_ids = _degenerate_total_equity_row_ids(cands)
    # B1-D1 (2026-08-30): reroute _CURRENT_STRICT drops to their non-current sibling
    # canonical (_NONCURRENT_SIBLING) instead of just discarding them. This MUST run as
    # a pre-pass over the whole `cands` dict, before the main per-canonical loop below -
    # canonical iteration order is not guaranteed, and adding a brand-new key to `cands`
    # mid-`for c, rows in cands.items()` would raise (dict changed size during
    # iteration); doing it inline per-canonical could also run before or after the
    # sibling's own turn. A pre-pass makes the reroute visible to the sibling's
    # resolution regardless of order.
    for _src, _sib in _NONCURRENT_SIBLING.items():
        _src_rows = cands.get(_src)
        if not _src_rows:
            continue
        # guard 1: sibling already has its own candidates (company disclosed it as a
        # separate line) -> don't add, or rule_additive_debt-style summing downstream
        # would double-count. Checked against cands' pre-reroute state, so the two
        # _NONCURRENT_SIBLING entries (disjoint src/dst pairs) can't interfere with
        # each other here.
        if cands.get(_sib):
            continue
        # guard 2 (not in the design doc's numbered list, but required for
        # correctness): only route rows that would ACTUALLY be dropped from `_src`'s
        # own resolution. _is_noncurrent() below (used by both _CURRENT_STRICT filter
        # sites, :1749/:1607) only narrows `rows` when a current-labeled candidate also
        # exists — "if every candidate is non-current (or unlabeled), rows is left
        # untouched" (see _is_noncurrent docstring), specifically so a current period
        # never ends up MISSING. In that all-non-current case the row still gets
        # confirmed as `_src` itself, so routing a copy to `_sib` too would double the
        # amount rather than recover it. Only reroute when `_src` actually has a
        # surviving current candidate.
        if not any(not _is_noncurrent(r) for r in _src_rows):
            continue
        # guard 3: only the section_path-only non-current class (see
        # _is_noncurrent_by_section_only docstring) - a label that already says
        # 장기/비유동 would have mapped straight to `_sib` on its own.
        _routed = [r for r in _src_rows if _is_noncurrent_by_section_only(r)]
        if _routed:
            cands[_sib] = list(_routed)
    # step3 fixup (2026-08-31, R58): the mirror-direction contamination
    # (_CURRENT_CONTAMINATED_NONCURRENT_SIBLING/_is_current_by_section_only, see their
    # comments above) — unlike the reroute above, here the ambiguous rows must be REMOVED
    # from `_src`'s own pool (not just copied to `_sib`), because `_src` is not a member
    # of _CURRENT_STRICT and has no later per-canonical filter to drop them on its own;
    # left in place they'd still conflict with the genuine noncurrent candidate that
    # triggered this branch in the first place.
    for _src, _sib in _CURRENT_CONTAMINATED_NONCURRENT_SIBLING.items():
        _src_rows = cands.get(_src)
        if not _src_rows:
            continue
        _current_rows = [r for r in _src_rows if _is_current_by_section_only(r)]
        if not _current_rows or len(_current_rows) == len(_src_rows):
            # nothing ambiguous here, or EVERY candidate is the ambiguous-current class —
            # in the latter case there's no genuine noncurrent candidate to protect, so
            # leave it as _src's own confirmed value (same MISSING-avoidance reasoning as
            # guard 2 above; net_debt is unaffected either way since both canonicals feed
            # the same _V3_ST_DEBT_PARTS/_V3_LT_DEBT_PARTS sum — see 00103130 in R58).
            continue
        if cands.get(_sib):
            continue  # sibling already has its own genuine candidates -> don't dup
        cands[_sib] = list(_current_rows)
        cands[_src] = [r for r in _src_rows if r not in _current_rows]
    for c, rows in cands.items():
        # ★R2 델타패치 실질화(2026-08-20, P3-1 재감사 후속): build_merged_lines() 의 셀
        # 키에 section_path 가 들어있어, 정정본이 표를 재렌더링해 section_path 가 원본과
        # 달라지면(흔함 — 예: 래퍼 한 겹 추가) 같은 라벨의 두 셀이 "같은 셀의 수정"이
        # 아니라 "다른 셀"로 살아남는다. 그러면 이 아래의 depth-우선(_reduce_conflict)이
        # section_path 가 얕은(=대개 원본) 쪽을 이겨버려, R2("정정이 이긴다")가 label
        # 단위에서는 무력화된다. 실측(고려아연 00102858 등, docs/qa/
        # gate_b_p3_depth_bug_2026-08-20.md): 원본 자산총계 12.046조가 2026-08-13 정정의
        # 11.769조를 이겨버린 사례로 확정.
        # ★label_raw 원문 그대로는 부족하다(2026-08-20 실측) — 정정본이 각주번호까지 같이
        # 바꾸는 경우가 흔하다("(5) 이익잉여금 (주27)" 원본 vs "(5) 이익잉여금" 정정본).
        # 그러면 label_raw 완전일치 그룹핑이 애초에 두 후보를 한 그룹으로 못 묶는다. 같은
        # norm()(번호/각주 제거, industry_profiles.norm — is.revenue grand-total 매칭에
        # 이미 쓰는 정규화)으로 묶는다.
        # BS grand-total: drop candidates from a confirmed trust-account sub-statement
        # (see _BS_GRAND_TOTAL / _trust_account_table_seqs above) *before* the by_label
        # grouping just below, not after (2026-08-20, P3-1 Track D fail_b 패턴A 후속 —
        # docs/plans/p3_1_trackd_failb_pattern_ab_fix_design_2026-08-20.md §1.3). Once the
        # grouping key below ignores label wording for these 3 canonicals, a trust-account
        # "자산총계" (legitimately 자산==부채 in its own sub-statement) could otherwise get
        # pooled into the same group as the real statement's total — filtering the
        # trust-account rows out first removes that risk. Only fires on the specific
        # trust-account signature — never a blanket table_seq preference.
        if c in _BS_GRAND_TOTAL and trust_seqs:
            filtered = [r for r in rows if r.get("table_seq") not in trust_seqs]
            if filtered:
                rows = filtered
        # bs.total_equity: drop EquityAndLiabilities-shaped rows masquerading as equity
        # (R51, 2026-08-27 — see _degenerate_total_equity_row_ids docstring) *before* the
        # by_label grouping / depth tiebreak below, same placement reasoning as trust_seqs
        # just above. Computed against `cands[c]` (pre-filter pool), not the possibly
        # already-narrowed `rows`, to stay consistent with how the id() set was built.
        if c == "bs.total_equity" and degenerate_eq_ids:
            filtered = [r for r in rows if id(r) not in degenerate_eq_ids]
            if filtered:
                rows = filtered
        # 여기서 depth 판정 *전에* 정규화 라벨 단위로 정리한다 — 같은 norm(label) 인데
        # 값이 다르고, 그중 amended=True(=더 나중 필링에서 값이 바뀐 셀)가 있으면, 그
        # 라벨의 amended=False(base) 후보는 버린다(= build_merged_lines() 가 원래
        # 하려던 edit을 대신 완성해준다). amended 후보가 없으면(=진짜 같은 필링 안의
        # 총계/하위항목 구조 차이) 손대지 않는다 — depth-우선은 그 목적에는 여전히
        # 유효하다.
        # ★[2026-08-20, 패턴A] BS 총계 3종(_BS_GRAND_TOTAL)은 라벨 표현이 통째로
        # 바뀌어도(예: "자산총계"→"자산") 같은 개념이라는 게 구조적으로 보장된다(한
        # 필링·basis 안에 "진짜" 총계는 하나뿐 — _trust_account_table_seqs와 같은
        # 전제). norm(label) 그룹핑은 표기 잡음(각주/공백)만 흡수하고 단어 자체가
        # 바뀌는 드리프트는 못 묶으므로(00103130/플레이그램 2017Q1 실측), 이 3종에
        # 한해 라벨을 무시하고 canonical 전체를 한 그룹으로 취급한다.
        by_label: dict[str, list[dict]] = defaultdict(list)
        for r in rows:
            key = "\0GRAND_TOTAL" if c in _BS_GRAND_TOTAL else _norm_label(r.get("label_raw"))
            by_label[key].append(r)
        stale_ids = set()
        for label, group in by_label.items():
            if not label or len(group) < 2 or len({g["value"] for g in group}) < 2:
                continue
            if not any(g.get("amended") for g in group):
                continue  # 진짜 총계/하위항목 구조차이 — depth-우선에 맡긴다
            stale_ids.update(id(g) for g in group if not g.get("amended"))
        if stale_ids:
            rows = [r for r in rows if id(r) not in stale_ids]
        # current-strict canonicals (trade_payables 등): drop non-current (장기/비유동)
        # candidates *before* stage ranking, not only inside _reduce_conflict(). A
        # non-current row can legitimately land on a higher mapping stage than the
        # correct current row (e.g. '장기매입채무및기타채무' is a registered exact alias
        # while '매입채무 및 기타유동채무' only reaches 'normalized' after whitespace
        # normalization) — when that happens top_vals below collapses to the single
        # (wrong) non-current value and _reduce_conflict() never runs at all, since it's
        # only invoked on a genuine top-stage tie. Fixes trade_payables near-zero fail_a
        # (52 rows/21 corps, 경남제약 00307028 등) — docs/qa/
        # gate_b_v3_fail_a_784_triage_2026-08-13.md ③. Only fires when a current-labeled
        # candidate actually exists; if every candidate is non-current (or unlabeled),
        # rows is left untouched — no current period can end up MISSING because of this.
        if c in _CURRENT_STRICT:
            cur_rows = [r for r in rows if not _is_noncurrent(r)]
            if cur_rows:
                rows = cur_rows
        # curated overrides (2026-08-13, see the two frozenset comments above): apply
        # BEFORE stage ranking, same reason as the _CURRENT_STRICT filter just above —
        # a component/child label commonly reaches stage='exact' (clean registered
        # alias) while the parent/total label only reaches 'normalized' (needs
        # whitespace/numbering normalization), so top_vals below would otherwise
        # collapse to the (curated-wrong) child value before _reduce_conflict() ever runs.
        if c == "is.revenue" and corp in _REVENUE_TOTAL_OVERRIDE_CORPS:
            grand = [r for r in rows
                     if _norm_label(r.get("label_raw")) in _REVENUE_TOTAL_LABELS and r["value"]]
            if grand:
                rows = grand
        if c == "bs.trade_payables" and corp in _TRADE_PAYABLES_PARENT_OVERRIDE_CORPS:
            parents = [r for r in rows if r.get("node_role") == "P" and r["value"]]
            if parents:
                rows = parents
        if c == "bs.trade_payables" and (corp, fy, period) in _TRADE_PAYABLES_ADDITIVE_OVERRIDE:
            want = _TRADE_PAYABLES_ADDITIVE_OVERRIDE[(corp, fy, period)]
            # ★the second (sibling) label maps to its OWN canonical (e.g. '기타지급채무'
            # -> bs.other_current_payables), never bs.trade_payables — the AccountMapper
            # alias table routes it there before _resolve() ever sees it (verified: LG화학
            # 실측, _map_label('기타지급채무','bs') -> account_code='bs.other_current_payables').
            # So `rows` (this canonical's own candidates) never contains it; must search
            # across every canonical's candidate list in `cands`, not just `rows`.
            all_rows = [r for rs in cands.values() for r in rs]
            picked = {}
            for r in all_rows:
                if _is_noncurrent(r):
                    continue
                label = _norm_label(r.get("label_raw"))
                for w in want:
                    if w not in picked and label.startswith(w):
                        picked[w] = r["value"]
            if len(picked) == len(want) and all(v is not None for v in picked.values()):
                confirmed[c] = sum(picked.values())
                continue
        # ★trade_payables stale-sub-line override (2026-08-21, R42 — see
        # _TRADE_PAYABLES_STALE_SUBLINE_OVERRIDE comment above): read from cands[c]
        # (the FULL pre-filter pool), not `rows` — for some keys (00146296/00364403 별도)
        # the verified-correct candidate is non-current and _CURRENT_STRICT above has
        # already dropped it from `rows` before this point ever runs.
        # ★0-valued duplicate guard (실측 2026-08-21, 코스나인 00442455 2021Q3): the SAME
        # rcept can carry the target label twice — once with the real value, once as a
        # spurious 0-valued duplicate row (parser table-dup, unrelated to R2/amendments).
        # Exclude 0 before checking for a single distinct value, same convention as
        # _reduce_conflict()'s shallowest-depth pool above.
        if c == "bs.trade_payables" and (corp, fy, period, basis) in _TRADE_PAYABLES_STALE_SUBLINE_OVERRIDE:
            want_label = _norm_label(_TRADE_PAYABLES_STALE_SUBLINE_OVERRIDE[(corp, fy, period, basis)])
            matches = [r for r in cands.get(c, [])
                       if _norm_label(r.get("label_raw")) == want_label and r["value"] not in (0, None)]
            vals = {r["value"] for r in matches}
            if len(vals) == 1:
                confirmed[c] = vals.pop()
                continue
        # is.sga stage-rank shortcut override (2026-08-15, Phase 1 — see
        # _SGA_SUBLINE_OVERRIDE_KEYS comment above): prefer the 판매비와관리비 sub-line
        # candidate over the polluted 영업비용 total, same placement/reasoning as the
        # two overrides just above (must run before stage ranking, not inside
        # _reduce_conflict(), since the total's stage='exact' already collapses
        # top_vals to a single (wrong) value before any conflict is ever detected).
        if c == "is.sga" and (corp, fy, period) in _SGA_SUBLINE_OVERRIDE_KEYS:
            sublines = [r for r in rows
                        if _norm_label(r.get("label_raw")) in _SGA_SUBLINE_LABELS and r["value"]]
            if sublines:
                rows = sublines
        # 가산 계열(ADDITIVE_CANON)은 한 canonical 에 여러 행이 정상적으로 대응한다
        # (cf.depreciation ← '감가상각비' + '투자부동산감가상각비'). 단일값 전제로 충돌
        # 판정하면 canonical 이 통째로 폐기되므로, 선언된 계열만 합산한다.
        # 성격 선언은 fin2/standardize/rules.py ADDITIVE_CANON 참조.
        if c in ADDITIVE_CANON:
            # ★합산이라고 품질 게이트를 건너뛰면 안 된다. 다만 어떤 게이트를 쓸지가 관건이다:
            #   · stage 로 거르면 너무 뭉툭하다 — 실측 OVER 32→8 이지만 정상 행이 잘려 MISSING 3→57
            #     (cf.depreciation 의 [exact]감가상각비 옆 [normalized]투자부동산감가상각비가 탈락).
            #   · 섹션(투자/재무활동)만 거르면 영업활동 안의 오매칭을 못 잡는다
            #     (실측 00102618: [fuzzy]'사용권자산손상차손'이 cf.rou_depreciation 에 붙음).
            #   → **의미 기반 라벨 가드**를 쓴다. classify_da_label 은 '손상차손'·'대손상각'·
            #     '누계액'·'상각후원가'를 배제하고 '유형자산의 증가'(=CAPEX)도 D&A 로 보지 않는다.
            #     본문과 주석이 **같은 라벨 어휘**를 공유하게 되는 이점도 있다.
            #   ※ 이 가드는 D&A 계열 전용이다. ADDITIVE_CANON 에 다른 계열(capex 등)을 넣으려면
            #     계열별 가드를 함께 선언해야 한다.
            total, seen = 0, set()
            for r in rows:
                if classify_da_label(r.get("label_raw") or "") is None:
                    continue
                v = r.get("value")
                if v is None:
                    continue
                key = ((r.get("label_raw") or "").strip(), v)
                if key in seen:      # 정정 병합으로 같은 셀이 중복될 수 있다
                    continue
                seen.add(key)
                total += abs(v)
            if total:
                confirmed[c] = total
            continue
        # is.controlling_ni/is.noncontrolling_ni: never let the stage-rank shortcut
        # confirm a split outright — always hold it as a conflict so
        # _resolve_ni_attribution (called right after _resolve()) gets a chance to
        # disambiguate via the net_income identity. See _NI_ATTRIBUTION_CANON above.
        if c in _NI_ATTRIBUTION_CANON:
            vals = {r["value"] for r in rows}
            if len(vals) == 1:
                confirmed[c] = next(iter(vals))
            else:
                conflicts[c] = sorted(rows, key=lambda r: (r["value"] is None, r["value"]))
            continue
        vals = {r["value"] for r in rows}
        if len(vals) == 1:
            confirmed[c] = next(iter(vals))
            continue
        best = max(_STAGE_RANK.get(r.get("stage"), 0) for r in rows)
        top = [r for r in rows if _STAGE_RANK.get(r.get("stage"), 0) == best]
        top_vals = {r["value"] for r in top}
        if len(top_vals) == 1:
            confirmed[c] = next(iter(top_vals))
            continue
        reduced = _reduce_conflict(c, top)
        if reduced is not None:
            confirmed[c] = reduced
            continue
        if c in CONSUMED_CANON:
            conflicts[c] = sorted(top, key=lambda r: (r["value"] is None, r["value"]))
    return confirmed, conflicts


def _top_stage_corroborated(rows: list[dict]):
    """>=2 raw candidates independently reach the single highest mapping stage AND agree
    on one value -> trust it. Phase 2 verification (2026-08-12, design doc §4-2-2) swept
    the full known-bug population (404 fail_a rows) and found this pattern in **zero** of
    them — the bug there is always the opposite shape (exactly one row at top stage,
    outranking a differing lower-stage one; see _resolve_ni_attribution docstring). This
    fires only as the fallback below, after the identity check has already failed or
    can't run, so it never overrides an identity-confirmed answer.

    Concretely this recovers the case where OCI happens to be ~0 for the period: the
    '당기순이익의 귀속' and '포괄손익의 귀속' sections then legitimately report the same
    number at the same (best) stage — two independent extractions agreeing is itself the
    corroboration, no need to know which section is which."""
    if len(rows) < 2:
        return None
    best = max(_STAGE_RANK.get(r.get("stage"), 0) for r in rows)
    top = [r for r in rows if _STAGE_RANK.get(r.get("stage"), 0) == best]
    if len(top) < 2:
        return None
    top_vals = {r["value"] for r in top}
    return next(iter(top_vals)) if len(top_vals) == 1 else None


_NI_IDENTITY_EPS = 2   # won tolerance for the identity match below (§C) — real filings
                       # occasionally carry a 1-won rounding gap between separately
                       # printed cells (measured, e.g. 01025644 2024Q1); negligible next
                       # to any realistic net-income magnitude, so it can't manufacture a
                       # false unique match on its own.


def _derive_net_income_from_ebt(cands: dict) -> set:
    """§A fallback anchor: when is.net_income has NO raw candidate at all (the total line
    is simply absent from this filing's body — measured ~12% of the still-held PASS
    sample, e.g. 00107987 2022FY), derive it as EBT − tax_expense for the sole purpose of
    anchoring the identity check below. Only fires when both are single, unambiguous
    candidates (never guesses among a split). Does NOT write into `confirmed` — net_income
    confirmation itself is out of this fix's scope, this value is only used locally here.

    ★2026-08-23(fy≥2024 잔여회귀 조사 — 펌텍코리아 00761059): is.tax_expense is NOT in
    `_LOSS_CANON`, so its stored sign is whatever the source document displays, and that
    display convention is NOT uniform across filings — some show it as a plain positive
    magnitude (EBT − tax = net_income), others show it already signed as a subtraction/
    benefit (EBT + tax = net_income, verified on a different real filing in this same
    population). There is no reliable way to tell which convention a given filing uses
    from the stored sign alone. Rather than guess, return BOTH candidate anchors — the
    caller's uniqueness-gated identity match already exists exactly to arbitrate between
    ambiguous candidates without guessing (결측 > 오염); a single spurious anchor typically
    just fails to find a match (safe), so offering two only helps when exactly one of them
    lands on a real, unique cni+nci pairing.

    ★2026-08-23(같은 조사 — 이오플로우 01274310): 원래는 tax 후보가 정확히 1개일 때만
    발동했는데, 일부 문서는 법인세비용 라인 자체가 없다(그 기간 법인세 자체가 없거나 0,
    'XI.법인세비용차감전순이익' 다음이 바로 귀속 라인). 그 모양(tax 후보 0개)을 '애매해서
    포기'와 똑같이 취급하면 EBT 자체가 net_income 이라는 뻔한 앵커조차 못 써서, 뒤이은
    _resolve_ni_attribution 의 identity 대조가 아예 못 돌고 noncontrolling_ni conflict 가
    안 풀린 채로 남는다(net_income 최종 폴백이 그 nci 를 0 취급 — A 계열과 동일 증상).
    tax 후보 0개는 '애매'가 아니라 '세금 자체가 없음'으로 보고 EBT 를 그대로 anchor 로
    쓴다(부호 애매성 없음 — 뺄 것이 없으므로)."""
    ebt = cands.get("is.ebt", [])
    if len(ebt) != 1:
        return set()
    e = ebt[0]["value"]
    tax = cands.get("is.tax_expense", [])
    if not tax:
        return {e}
    if len(tax) == 1:
        t = tax[0]["value"]
        return {e - t, e + t} if t else {e - t}
    return set()


def _match_ni_identity(cni_vals: set, nci_vals: set, net_income: int):
    """cni × nci pair whose sum matches net_income, exact first, else (§C) within
    _NI_IDENTITY_EPS — but only if the epsilon relaxation still yields a UNIQUE pair.
    Multiple exact matches (a real ambiguity, e.g. two candidate pairs both landing on
    net_income by coincidence) short-circuits straight to "no answer" without trying
    epsilon, since relaxing further can only make that ambiguity worse."""
    exact = {(c, n) for c in cni_vals for n in nci_vals if c + n == net_income}
    if len(exact) == 1:
        return next(iter(exact))
    if exact:
        return None
    near = {(c, n) for c in cni_vals for n in nci_vals if abs(c + n - net_income) <= _NI_IDENTITY_EPS}
    return next(iter(near)) if len(near) == 1 else None


def _resolve_ni_attribution(cands: dict, confirmed: dict, conflicts: dict) -> None:
    """2nd pass (Phase B, docs/plans/std_v3_controlling_ni_gap_fix_plan_2026-08-08.md §3-2):
    re-select a held is.controlling_ni conflict via the accounting identity
    controlling_ni + noncontrolling_ni = net_income, falling back to same-stage
    cross-candidate corroboration (_top_stage_corroborated) when that identity can't run
    or can't disambiguate.

    Root cause (§1-B/§1-B-부록): the alias catalog has bare labels ('지배기업
    소유주지분'·'비지배지분') that legitimately appear in BOTH the '당기순이익의 귀속'
    section (what we want) and the '포괄손익의 귀속' section (총포괄이익 몫, wrong
    concept) — both exact-match the same canonical, so _resolve() above holds instead
    of guessing. Cross-matching the candidate pairs against the already-confirmed
    net_income disambiguates without guessing (mutates confirmed/conflicts in place).

    Deliberately NOT a section_path text filter ('포괄' 있으면 버림): measured
    (2026-08-08) that ~0.5% of filings have the two section labels literally swapped
    in the source (DH오토웨어 00110583 2022H1, 에프알텍 00442561 2017H1) — a text
    filter would pick the wrong candidate there, while the identity check still finds
    the right one because it's anchored to the actual net_income value, not a label.

    Fallback #1 (added 2026-08-12, Phase 2 verification §4-2-2/§4-2-3): the identity check
    needs both net_income confirmed AND a clean controlling/noncontrolling value pairing
    — measured ~28% of a 5,000-row PASS-population re-check had a stage-rank-confirmed
    value (from _resolve()'s pre-fix behavior) get dropped to NULL here purely because
    net_income was missing or the real noncontrolling_ni candidate had been misclassified
    into the controlling_ni pool for that filing (unrelated data-quality gaps, not this
    fix). _top_stage_corroborated recovers those without reintroducing the original bug
    (verified absent from the 404-row known-bug population — see its docstring).

    Fallback #2 (added 2026-08-12, same-day follow-up): re-examining what was STILL held
    after fallback #1 found three more low-risk, independently-gated recovery paths —
    §A always also tries EBT−tax_expense as a net_income anchor when the direct line is
    missing (_derive_net_income_from_ebt); §B always also tries nci=0 in addition to
    whatever noncontrolling_ni candidate(s) exist (small/negligible NCI can still pick up
    an unrelated noisy candidate for that canonical); §C allows a small rounding-level
    epsilon (_NI_IDENTITY_EPS) when no exact pair matches. Measured recovery on the same
    5,000-row sample: A 12% / B 24% / C 3% of the still-NULL bucket, each still requiring
    a UNIQUE resulting pair to fire — an ambiguous result (e.g. two pairs both landing on
    net_income) still correctly stays held.

    If nothing disambiguates (identity ambiguous/impossible AND no multi-row stage
    corroboration — the '단독 후보' pattern from §1-A), stays held (결측 > 오염, no
    guessing).

    ★Fallback #3 (2026-08-23, fy≥2024 잔여회귀 조사 중 발견 — 펌텍코리아 00761059 등):
    entry used to require is.controlling_ni ITSELF in conflicts. But the same bare-label
    NI-attribution-vs-TCI-attribution ambiguity (see module docstring above) can hit
    is.noncontrolling_ni ALONE while is.controlling_ni already resolved cleanly (a single,
    unambiguous qualified label like '지배기업의 소유주에게 귀속되는 당기순이익') —
    common precisely when account_mapper's bare-alias guard (2026-08-22 fix) already
    stripped the controlling-side bare label but a bare '비지배지분' on the noncontrolling
    side still collides with its own TCI counterpart. Previously the identity check never
    even ran for that shape, leaving is.noncontrolling_ni held in conflicts; the net_income
    blind fallback below then read `confirmed.get("is.noncontrolling_ni", 0)` and silently
    treated a REAL, merely-unresolved NCI as 0 — net_income == controlling_ni exactly,
    wrong. Now the entry fires whenever EITHER canonical is in conflicts, and cni_vals is
    built with the same confirmed>conflicts>cands precedence nci_vals already used (so an
    already-clean controlling_ni contributes its single confirmed value instead of KeyError
    on an empty conflicts entry)."""
    if "is.controlling_ni" not in conflicts and "is.noncontrolling_ni" not in conflicts:
        return
    matched = False
    net_income = confirmed.get("is.net_income")

    cni_vals = set()
    if "is.controlling_ni" in confirmed:
        cni_vals.add(confirmed["is.controlling_ni"])
    elif "is.controlling_ni" in conflicts:
        cni_vals |= {r["value"] for r in conflicts["is.controlling_ni"]}
    elif "is.controlling_ni" in cands:
        cni_vals |= {r["value"] for r in cands["is.controlling_ni"]}

    nci_vals = set()
    if "is.noncontrolling_ni" in confirmed:
        nci_vals.add(confirmed["is.noncontrolling_ni"])
    elif "is.noncontrolling_ni" in conflicts:
        nci_vals |= {r["value"] for r in conflicts["is.noncontrolling_ni"]}
    elif "is.noncontrolling_ni" in cands:
        nci_vals |= {r["value"] for r in cands["is.noncontrolling_ni"]}
    nci_vals.add(0)   # §B: wholly-owned/negligible-NCI is always a candidate pairing,
                      # even when some other (possibly unrelated/noisy) candidate
                      # exists for this canonical too — mirrors the old sole-fallback
                      # (v2's `nci or 0`), just no longer gated on "nothing else found".

    def _try_anchors(anchors: set) -> bool:
        # §A/tax-sign ambiguity: multiple anchors possible (see _derive_net_income_from_ebt).
        # Only accept if exactly one anchor yields a match — 2+ distinct matches across
        # anchors is a real ambiguity (which anchor was even right?), not a resolution.
        if not anchors:
            return False
        matches = {_match_ni_identity(cni_vals, nci_vals, ni) for ni in anchors}
        matches.discard(None)
        match = matches.pop() if len(matches) == 1 else None
        if match is None:
            return False
        c_val, n_val = match
        if "is.controlling_ni" in conflicts:
            confirmed["is.controlling_ni"] = c_val
            del conflicts["is.controlling_ni"]
        if "is.noncontrolling_ni" in conflicts:
            confirmed["is.noncontrolling_ni"] = n_val
            del conflicts["is.noncontrolling_ni"]
        return True

    if net_income is not None:
        matched = _try_anchors({net_income})
    else:
        # R44 §B: try the continuing+discontinued TOTAL-line sum anchor (see
        # _derive_net_income_from_continuing_discontinued's docstring) FIRST, on
        # its own — never unioned with §A (unioning lets §A's own, possibly
        # scope-mismatched, match compete and re-introduce the very ambiguity §B
        # exists to resolve — measured on DRB동일 00118266 FY2012, whose EBT is
        # itself silently continuing-only-scoped with no textual marker at all,
        # the original bug). §B's own function already self-suppresses (returns
        # None) when a directly-reported plain headline line exists and disagrees
        # with the continuing+discontinued sum (00401731 2011H1/Q3: a '중단영업
        # 이익(손실)' static memo figure genuinely excluded from the real
        # headline) or when the headline itself is ambiguous (00103547 2020Q1:
        # two differently-scoped '당기순이익'/'분기순이익' lines coexist, neither
        # textually distinguishable as "the" headline).
        #
        # ★When §B produces an anchor but it does NOT actually match anything
        # (00238782 2014Q3, found in the R45 436→1,440-corp full backfill
        # verification, docs/plans/gateb_r44_resolve_redesign_2026-08-25.md §3.6):
        # no plain headline line exists to trigger §B's self-suppression, yet this
        # filer's own attribution breakdown (controlling+noncontrolling) turns out
        # to be continuing-only-scoped too (matches §A's EBT−tax anchor exactly,
        # NOT the continuing+discontinued sum) — §B alone finds no match at all
        # and, left there, would wrongly leave noncontrolling_ni held (silently
        # defaulting to 0 in net_income's own fallback). Falling back to §A here
        # (sequentially, only once §B has already had its unmatched turn — not
        # unioned, so DRB동일's competing §A match is still never even attempted
        # there since §B succeeds on its own first) recovers the correct pairing.
        _b_anchor = cands.get("__ni_total_anchor__")
        if _b_anchor:
            matched = _try_anchors({_b_anchor[0]["value"]})
        if not matched:
            matched = _try_anchors(_derive_net_income_from_ebt(cands))  # §A
    if matched:
        return
    # identity couldn't run or couldn't disambiguate -> try stage corroboration per
    # canonical independently (controlling_ni and noncontrolling_ni are unrelated events
    # here — one may corroborate while the other stays genuinely ambiguous).
    if "is.controlling_ni" in conflicts:
        cv = _top_stage_corroborated(conflicts["is.controlling_ni"])
        if cv is not None:
            confirmed["is.controlling_ni"] = cv
            del conflicts["is.controlling_ni"]
    if "is.noncontrolling_ni" in conflicts:
        nv = _top_stage_corroborated(conflicts["is.noncontrolling_ni"])
        if nv is not None:
            confirmed["is.noncontrolling_ni"] = nv
            del conflicts["is.noncontrolling_ni"]


# P&L 결과 계정(손실이 될 수 있음). 순'손실' 단독 라벨(이익 없음)에 양수값이면 손실을 양(+)으로
# 기재한 서식(루닛 2021 'V.당기순손실'=+73.6B 등) → 표준화 시 부호반전. 이미 음수(괄호기재)이거나
# 결합라벨('이익(손실)')·이익 라벨은 그대로. 실측: 손실단독 net_income 음수 1098 vs 양수 90(7.6%).
_LOSS_CANON = frozenset({
    "is.net_income", "is.operating_income", "is.ebt",
    "is.controlling_ni", "is.gross_profit",
})


def _loss_signed(canon: str, label: str, value):
    """순'손실' 단독 라벨 + 양수 → −value(손실). 그 외는 원값."""
    if (value is not None and value > 0 and canon in _LOSS_CANON
            and label and "손실" in label and "이익" not in label):
        return -value
    return value


def _is_cogs_labeled(label_raw: str | None) -> bool:
    """True if the raw label text itself reads as a cost-of-sales line ('...매출원가').
    Used only as a label-collision tiebreak in `_cogs_additive_labels()` (see there)."""
    return bool(label_raw) and "매출원가" in label_raw


def _cogs_additive_labels(merged: list[dict], period: str, basis: str,
                          want: tuple[str, ...]) -> dict[str, int]:
    """Recover raw values for `want` (normalized label text) directly from `merged`,
    bypassing _map_rows()/AccountMapper entirely — see _COGS_ADDITIVE_OVERRIDE comment
    for why this must NOT go through the global alias table. Mirrors _map_rows()'s
    statement/basis filter + H1/Q3 cumulative-only dedup (same interim/cum_seen logic),
    just keyed by normalized label text instead of mapped canonical.

    ★라벨충돌 가드(2026-08-15, 00143527/00163673 실측 버그수정, R21 부기): `_norm_label()`은
    라벨을 첫 '(' 에서 자른다("영업이익(손실)"→"영업이익" 처럼 후행괄호를 벗기는 게 목적).
    그런데 "기타수익(매출액)에 대한 매출원가"(진짜 COGS 서브라인)처럼 괄호 뒤에 텍스트가 더
    있는 라벨은 "기타수익(매출액)"(매출액 세부내역, 전혀 다른 계정)·"기타수익"(별개의 손익
    항목)과 같은 정규화 키로 충돌한다. 319개 override 키 전수 스캔(2026-08-15) 결과 31개 키가
    이 충돌에 노출돼 있었고 그중 5개는 실제로 틀린 값이 픽업됐다(4개는 2024년 이전이라 XBRL
    커버리지가 없어 Gate B도 못 잡던 침묵오염 — 00163673 2017FY/2018FY/2018H1/2019Q1).
    이 override 의 want 라벨은 전부 "매출원가류" 개념이므로, 같은 정규화 키에 라벨 텍스트가
    2개 이상 붙으면 원문에 '매출원가' 부분문자열을 포함하는 쪽을 신뢰한다 — 실측 31건 전부
    이 규칙 하나로 모호함 없이(그룹당 정확히 1개) 갈렸다. 그런 후보가 없거나 여럿이면(관측된
    바 없음, 미지 케이스) 기존 동작(마지막 매칭 값 승)을 그대로 유지 — 방어적으로만 개입,
    새로운 오탐을 만들지 않는다."""
    interim = period in ("H1", "Q3")
    picked: dict[str, int] = {}
    cum_seen: set[str] = set()
    for r in merged:
        if r["statement"] != "IS" or r["basis"] != basis:
            continue
        label = _norm_label(r.get("label_raw"))
        if label not in want:
            continue
        is_cum = r.get("is_cumulative", False)
        if interim:
            if is_cum:
                if label not in cum_seen:
                    picked.pop(label, None)
                    cum_seen.add(label)
            elif label in cum_seen:
                continue
        if r.get("value_won") is None:
            continue
        if label in picked and not _is_cogs_labeled(r.get("label_raw")):
            continue   # 이미 채택된 값이 있는데 이번 후보가 '매출원가' 라벨이 아니면 덮어쓰지 않음
        picked[label] = r["value_won"]
    return picked


def _ni_attribution_structural_candidates(rows: list[dict], period: str,
                                          basis: str) -> dict[str, list[dict]]:
    """Structural recovery for is.controlling_ni/is.noncontrolling_ni — mismap fix,
    docs/plans/std_v3_controlling_ni_mismap_structural_fix_design_2026-08-15.md §2.

    Root cause (§1): AccountMapper matches report_lines rows to a canonical by label
    text alone, and the source document sometimes breaks that assumption for the NI
    attribution lines — either reusing the parent line's own label for the controlling-
    interest sub-line (Samsung Electronics: label literally '분기순이익', section
    '분기순이익의 귀속'), or a fuzzy match routing a '지배'-labeled line into
    is.noncontrolling_ni instead (동성케미컬). Either way the correct candidate never
    enters is.controlling_ni's pool at all — it lands in is.net_income's or
    is.noncontrolling_ni's pool instead, leaving is.controlling_ni with a single
    (wrong, OCI-section) candidate that _resolve()'s NI_ATTRIBUTION_CANON branch
    auto-confirms outright (len(vals)==1 never reaches `conflicts`, so
    _resolve_ni_attribution's identity safety net never even gets called).

    This function does NOT pick a value — it only widens the candidate pool. It reads
    section_path (structure), not label text (which is what's unreliable here): within
    a NET-INCOME attribution section ('귀속' + '순이익' in the path, '포괄' excluded —
    the comprehensive-income attribution section must NOT match), if exactly one member
    row's label contains '비지배' and exactly one doesn't, the '비지배' row is an
    is.noncontrolling_ni candidate and the other is an is.controlling_ni candidate,
    regardless of what its own label says. Any other shape (0 or 2+ '비지배' rows, a
    section with only 1 or 3+ members) is silently skipped — no guessing (결측>오염).

    Measured (read-only probe, full 78-row known-bug population, 2026-08-15): fires on
    32/51 mismap rows, 0 false positives (recovered value always matched Gate B's
    independent XBRL-derived report_won). The stage-rank shortcut is already skipped
    for these two canonicals (_NI_ATTRIBUTION_CANON) — extending the pool here just
    ensures the multi-value split it now sees is genuinely useful (correct-vs-wrong,
    not wrong-vs-wrong), and lets the already-verified net_income identity
    (_resolve_ni_attribution, 5dbecac) pick between them exactly as it does for any
    other multi-candidate split.

    Mirrors _map_rows()'s IS/basis filter + H1/Q3 cumulative-only convention (same
    reasoning: an interim filing prints both quarterly and cumulative cells for the
    same line, and std_v2 convention keeps only the cumulative one for is./cf.)."""
    interim = period in ("H1", "Q3")
    is_rows = [r for r in rows if r["statement"] == "IS" and r["basis"] == basis]
    if interim:
        cum_rows = [r for r in is_rows if r.get("is_cumulative")]
        if cum_rows:
            is_rows = cum_rows

    sections: dict[tuple, list] = defaultdict(list)
    for r in is_rows:
        sp = r.get("section_path") or ""
        # ★2026-08-23(fy≥2024 잔여회귀 조사 — 모트렉스 00876908): '귀속' 요구가 너무 좁았다.
        # 일부 문서는 귀속 섹션을 '…의 귀속'류 별도 문구 대신 **부모 순이익 총계 라인
        # 자신의 라벨**을 그대로 section_path 로 재사용한다(예: section_path='당기순이익
        # (손실)', '귀속' 단어 자체가 없음) — 이 모양은 이전엔 스캔에서 통째로 빠져,
