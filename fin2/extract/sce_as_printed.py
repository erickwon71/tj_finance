def apply_as_printed_cells(lines: List, rcept_no: str) -> int:
    """Restore the as-printed value in the listed cells. Returns the number of cells rewritten."""
    if not rcept_no:
        return 0
    n = 0
    for ln in lines:
        if ln.statement != "SCE" or ln.value_won is None:
            continue
        pair = _AS_PRINTED_CELLS.get((rcept_no, ln.basis, (ln.label_raw or "").strip(), ln.col_label or "", ln.row_order))
        if pair is not None and ln.value_won == pair[0]:
            ln.value_won = pair[1]
            n += 1
    if n:
        logger.debug(f"[R206] {rcept_no}: {n} cells loaded as printed")
    return n
