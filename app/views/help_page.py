"""도움말 페이지 — 기업명 옆 특별조치 각주(주n) 및 표시 기준 설명.

각주 정의는 `app.format.CORP_NOTES` 단일 출처를 그대로 렌더한다(마커와 설명이 항상 동기화).
"""
from __future__ import annotations

import streamlit as st

from app.format import CORP_NOTES


def render() -> None:
    st.header("ℹ️ 도움말 — 표시 기준 안내")
    st.caption("기업명 옆의 **(주n)** 마커는 해당 기업 수치에 특별한 조치가 적용됐음을 뜻합니다. "
               "각 표시의 의미는 아래와 같습니다.")

    st.subheader("기업명 옆 각주(주n)")
    for key, desc in CORP_NOTES.items():
        st.markdown(f"- **({key})** {desc}")

    st.divider()

    st.subheader("연결 / 별도 기준")
    st.markdown(
        "- **연결(consolidated)**: 지배기업과 종속기업을 하나로 합친 재무제표. 그룹 전체 실적을 봅니다.\n"
        "- **별도(개별, separate)**: 지배기업 단독 재무제표. 종속기업이 없거나 연결을 작성하지 않는 "
        "기업은 별도만 존재합니다. 연결을 요청했으나 없을 때 별도로 대체되면 **(주2)**로 표시합니다."
    )

    st.subheader("달력분기(CQ) vs 회계연도(FY)")
    st.markdown(
        "- 기업마다 결산월이 다릅니다(대부분 12월, 일부 3·6·9월 등). 서로 다른 결산월 기업을 같은 "
        "시점으로 비교하기 위해, 분기·비교 화면은 각 사의 회계분기를 **달력분기(1~3월=CQ1, 4~6월=CQ2, "
        "7~9월=CQ3, 10~12월=CQ4)로 재배치**해 보여줍니다.\n"
        "- 12월 결산 기업은 회계=달력이 동일합니다. **비-12월 결산 기업**은 인접한 두 회계연도 조각을 "
        "합성(recomposed)하므로 회사가 보고한 **회계연도(FY)와 기간·값이 다를 수 있습니다** → **(주1)**.\n"
        "- 반면 **기업 시각화의 '연간' 탭**은 회사가 실제 보고한 **회계연도(FY) 원본**을 그대로 보여줍니다. "
        "따라서 비-12월 결산 기업은 '연간(FY)' 값과 '분기 합산(달력 CY)' 값이 서로 다를 수 있습니다(둘 다 정상)."
    )
