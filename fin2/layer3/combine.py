def _map_rows(rows, period: str, basis: str, statements,
             corp: str | None = None, fy: int | None = None) -> dict[str, list[dict]]:
    """Map merged cell dicts → {canonical: [candidate]}. Shared by both paths.
    Interim (H1/Q3) flow (is./cf.) keeps cumulative cells only (std_v2 convention).
    Carries the amendment marker (amended/amended_by) onto each candidate.

    corp/fy: current corp_code/fiscal_year, optional — needed only to gate the T3(R29)
    K-GAAP headline-NI recovery below (mirrors `_resolve()`'s corp/fy params). Callers
    that omit them get the old behavior unchanged (no-op)."""
    interim = period in ("H1", "Q3")
    cands: dict[str, list[dict]] = defaultdict(list)
    cum_seen: set[str] = set()
    stmt_set = set(statements)
    for r in rows:
        if r["statement"] not in stmt_set or r["basis"] != basis:
            continue
        fs = _FS.get(r["statement"])
        res = _map_label(r["label_raw"], fs)
        if res.confidence < 0.88 or res.account_code.startswith("unknown."):
            continue
        c = res.account_code
        # is.revenue fuzzy-containment false positives (R52, 2026-08-27 — see
        # docs/plans/gateb_r52_revenue_cogs_note_mismap_design_2026-08-27.md).
        # AccountMapper._fuzzy_match()'s short-alias guard only protects aliases
        # <=4 chars, so two longer-but-still-short exact aliases slip through via
        # containment:
        #  (a) "수익(매출액)"(7자, exact alias for a bare revenue-total line) is a
        #      substring of IFRS15 매출유형별 disaggregation-note COGS rows like
        #      "재화의 판매로 인한 수익(매출액)에 대한 매출원가" — a COST line, not
        #      revenue (실측 291개사/9,698행 원문에 이 문구 존재). Can't fix by
        #      dropping the alias itself: 1,725개사/71,518행 use it verbatim as their
        #      real revenue-total label (load-bearing, exact stage elsewhere).
        #  (b) "보험판매수입수수료"(9자, insurance-agency commission-income alias) has
        #      a bare "수입수수료"(commission income — any industry, e.g.
        #      새론오토모티브/00305668 자동차부품) as its suffix substring; matches
        #      even for non-insurance filers with no "보험" context at all (실측
        #      279개사/3,303행).
        # Both only corrupt std_v3 when they end up the SOLE is.revenue candidate for
        # a period (the real total line, if present, wins via _resolve()'s stage-rank
        # shortcut regardless) — but that's exactly what happened in the 21-row fail_a
        # cluster this guard was written for. Scoped to is.revenue+stage='fuzzy' only —
        # doesn't touch the general matcher (a blanket threshold change was rejected:
        # 232 catalog-level alias collisions in the same escape zone, many already
        # hand-guarded by the R44~R49 controlling_ni/noncontrolling_ni series — raising
        # the threshold globally risks interacting with that tuning unpredictably).
        if c == "is.revenue" and res.stage == "fuzzy":
            label = r["label_raw"] or ""
            if "매출원가" in label:
                continue
            if res.matched_alias == "보험판매수입수수료" and "보험" not in label:
                continue
        is_cum = r["is_cumulative"]
        flow = interim and (c.startswith("is.") or c.startswith("cf."))
        if flow:
            if is_cum:
                if c not in cum_seen:
                    cands.pop(c, None)
                    cum_seen.add(c)
            elif c in cum_seen:
                continue
        cands[c].append({
            "value": _loss_signed(c, r["label_raw"], r["value_won"]),
            "stage": res.stage, "label_raw": r["label_raw"],
            "node_role": r["node_role"], "section_path": r["section_path"],
            "table_seq": r["table_seq"], "is_cumulative": is_cum,
            "amended": r.get("amended", False), "amended_by": r.get("amended_by"),
        })
    # is.controlling_ni/is.noncontrolling_ni structural recovery (mismap fix,
    # 2026-08-15 — see _ni_attribution_structural_candidates docstring). IS-only, so
    # only relevant when this call's statement scope includes IS.
    if "IS" in stmt_set:
        for c, extra_rows in _ni_attribution_structural_candidates(rows, period, basis).items():
            cands[c].extend(extra_rows)
        # R44 §B — net_income anchor carrier, NOT a real DIRECT_MAP canonical. Read
        # only by _resolve_ni_attribution() below; harmlessly no-ops through
        # _resolve()'s generic loop otherwise (DIRECT_MAP.get() on this key is None,
        # so it never reaches `col`). See _derive_net_income_from_continuing_
        # discontinued's docstring for why this anchor is preferred over EBT−tax.
        _ni_total_anchor = _derive_net_income_from_continuing_discontinued(rows, period, basis)
        if _ni_total_anchor is not None:
            cands["__ni_total_anchor__"] = [{"value": _ni_total_anchor}]
        # T3(R29) — only when the caller identified corp/fy AND is.net_income has no
        # candidate at all yet (conservative default, §4-4 (e): an existing candidate
        # from any other path is trusted over this one).
        if corp is not None and fy is not None and not cands.get("is.net_income"):
            for c, extra_rows in _kgaap_headline_ni_candidates(rows, corp, fy, period, basis).items():
                cands[c].extend(extra_rows)
    return dict(cands)


def collect_candidates(session, corp: str, fy: int, period: str, basis: str,
                       statements=("BS", "IS"),
                       rcept_by_stmt: dict[str, str] | None = None) -> dict[str, list[dict]]:
    """Map current-year (col_index=0) report_lines to {canonical: [candidate]} by
    querying report_lines directly (diagnostic / ablation path).

    rcept_by_stmt: optional {statement: rcept_no} to restrict each statement to a
    single filing. Without it, ALL filings for the period are pooled — which pools
    original + amendment/restatement versions and produces spurious conflicts.
    combine() uses build_merged_lines() instead (delta-patch); this stays for the
    ablation/pooled diagnostics.
    """
    rows = []
    for statement in statements:
        params = {"c": corp, "y": fy, "p": period, "b": basis, "s": statement}
        rcept_clause = ""
        if rcept_by_stmt and rcept_by_stmt.get(statement):
            rcept_clause = " AND rcept_no = :r"
            params["r"] = rcept_by_stmt[statement]
        db_rows = session.execute(text(f"""
            SELECT label_raw, value_won, node_role, section_path, table_seq,
                   COALESCE(is_cumulative, false) AS is_cum
            FROM report_lines
            WHERE corp_code=:c AND report_fiscal_year=:y AND report_fiscal_period=:p
              AND basis=:b AND statement=:s AND col_index=0 AND value_won IS NOT NULL
              AND header_hint IS NULL          -- F2 가드(위와 같은 이유)
              {rcept_clause}
        """), params).fetchall()
        for label_raw, value_won, node_role, section_path, table_seq, is_cum in db_rows:
            rows.append({
                "statement": statement, "basis": basis, "label_raw": label_raw,
                "value_won": int(value_won), "node_role": node_role,
                "section_path": section_path, "table_seq": table_seq,
                "is_cumulative": bool(is_cum),
            })
    return _map_rows(rows, period, basis, statements, corp=corp, fy=fy)


def combine(session, corp: str, fy: int, period: str, basis: str,
            rcept_by_stmt: dict[str, str] | None = None,
            select_filing: bool = True, statements=("BS", "IS")):
    """Assemble std columns for one period. Returns (col, conflicts).

    col: {std_column: value} for DIRECT_MAP canonicals that resolved to a single
    value. conflicts: {canonical: [held candidates]} for analysis.

    Default path (L3-1b, 정본 정책): build_merged_lines() — 최초등록본 + 순차 델타
    패치(기재정정 반영 표시 포함). This removes spurious conflicts from pooling
    versions AND preserves untouched base cells under partial amendments.

    rcept_by_stmt: explicit {statement: rcept_no} bypasses the merge (ablation).
    select_filing=False + no rcept_by_stmt: pool all filings (diagnostic).
    """
    col, conflicts, _prov = combine_full(
        session, corp, fy, period, basis,
        rcept_by_stmt=rcept_by_stmt, select_filing=select_filing, statements=statements)
    return col, conflicts


def combine_full(session, corp: str, fy: int, period: str, basis: str,
                 rcept_by_stmt: dict[str, str] | None = None,
                 select_filing: bool = True, statements=("BS", "IS", "CF"),
                 merged: list[dict] | None = None):
    """Like combine() but also returns provenance (for std_v3 build, L3-3).

    Returns (col, conflicts, prov) where prov = {
      basis_fallback: bool,
      amended_cols:   [std_col, ...]         # value came from a 기재정정-patched cell
      amend_chain:    {std_col: [rcept,...]} # which amendments touched it
    }. source_rcepts is resolved by the caller (build) from the merged filings.

    merged: pre-built build_merged_lines() result. Pass it to reuse the (basis-
    independent) delta-patch merge across both bases — halves the query cost in
    the full build.
    """
    prov = {"basis_fallback": False, "amended_cols": [], "amend_chain": {}}
    if rcept_by_stmt is not None:
        cands = collect_candidates(session, corp, fy, period, basis,
                                   statements=statements, rcept_by_stmt=rcept_by_stmt)
    elif select_filing:
        if merged is None:
            merged = build_merged_lines(session, corp, fy, period)
        cands = _map_rows(merged, period, basis, statements, corp=corp, fy=fy)
        # L3-2 basis fallback: a company with no subsidiaries files only 별도(separate);
        # its 연결(consolidated) figures = separate. When the requested basis is entirely
        # absent but the period has only the other basis, fall back (verified: 45/45 such
        # cases are single-basis companies whose other-basis value == std_v2). Mirrors the
        # old chain (consolidated→separate for non-consolidating corps).
        if not cands:
            other = "separate" if basis == "consolidated" else "consolidated"
            bases_present = {r["basis"] for r in merged}
            if bases_present == {other}:
                cands = _map_rows(merged, period, other, statements, corp=corp, fy=fy)
                prov["basis_fallback"] = True
    else:
        cands = collect_candidates(session, corp, fy, period, basis,
                                   statements=statements)
    confirmed, conflicts = _resolve(cands, corp, fy, period, basis)
    _resolve_ni_attribution(cands, confirmed, conflicts)
    # ★net_income conflict disambiguation via NI identity (2026-08-22, P1C 잔여회귀 조사 중
    # 발견 — 00120526 2014Q3 / 00139214 2013Q1). is.net_income can end up with 2+ raw
    # candidates instead of a clean single value: (a) an amendment chain where a later
    # filing re-labels the same total-NI line with different wording (section_path 불일치
    # → build_merged_lines 의 cell-identity 키가 서로 다른 셀로 취급, 예: '당기순이익(손실)의
    # 귀속' vs '분기순이익의 귀속'), or (b) a supplementary/regulatory-adjusted income figure
    # printed alongside the real statement (보험사의 '대손준비금 반영후 조정이익' 부기 등,
    # Roman-numeral 헤더가 둘 다 있어 둘 다 본문 후보로 잡힘). `_resolve_ni_attribution` above
    # already resolved is.controlling_ni via the same identity in the OTHER direction
    # (cni×nci→net_income); this reuses it symmetrically (net_income candidates→cni+nci) to
    # pick whichever conflicting net_income value is actually consistent with the resolved
    # attribution — never guessing among unrelated candidates (0 or 2+ matches → leave the
    # conflict, don't confirm).
    if ("is.net_income" not in confirmed and "is.net_income" in conflicts
            and "is.controlling_ni" in confirmed):
        cni = confirmed["is.controlling_ni"]
        # broaden nci to whatever's available, same precedence as _resolve_ni_attribution's
        # nci_vals above (confirmed > held conflict > raw candidates), plus 0 (wholly-owned).
        nci_vals = set()
        if "is.noncontrolling_ni" in confirmed:
            nci_vals.add(confirmed["is.noncontrolling_ni"])
        elif "is.noncontrolling_ni" in conflicts:
            nci_vals |= {r["value"] for r in conflicts["is.noncontrolling_ni"]}
        elif "is.noncontrolling_ni" in cands:
            nci_vals |= {r["value"] for r in cands["is.noncontrolling_ni"]}
        nci_vals.add(0)
        qualifying = {r["value"] for r in conflicts["is.net_income"]
                      if any(abs(cni + n - r["value"]) <= _NI_IDENTITY_EPS for n in nci_vals)}
        if len(qualifying) == 1:
            confirmed["is.net_income"] = qualifying.pop()
            del conflicts["is.net_income"]
    # net_income fallback (ported from fin2/standardize/rules.py::rule_net_income_fill,
    # missing from the v3 port — 실측 2026-08-09: 삼성증권 FY2025 등 470행/119개사).
    # A nonstandard total-NI label (e.g. '보통주 당기순이익' instead of '당기순이익') can
    # fail to match is.net_income while the attribution lines (controlling/noncontrolling —
    # distinct labels, reliably matched) still resolve. Recompose the total from those
    # rather than leaving it NULL. Non-controlling defaults to 0 (e.g. 별도, no subsidiaries).
    # ★2026-08-22: gate on `"is.net_income" not in cands` (아예 후보가 없을 때만), not just
    # "not in confirmed" — the old condition also matched an *unresolved conflict* (multiple
    # candidates exist, none picked) and silently overwrote it with a guess equal to
    # controlling_ni alone (nci defaults to 0 when noncontrolling_ni is also unconfirmed),
    # which is exactly the wrong-value bug above when the identity check just above didn't
    # already resolve it. A genuine conflict should stay a conflict (NULL), not become a
    # confident-looking wrong number.
    if ("is.net_income" not in confirmed and "is.net_income" not in cands
            and "is.controlling_ni" in confirmed):
        nci = confirmed.get("is.noncontrolling_ni", 0)
        confirmed["is.net_income"] = confirmed["is.controlling_ni"] + nci
    col: dict[str, int] = {}
    for canon, value in confirmed.items():
        std_col = DIRECT_MAP.get(canon)
        if std_col is None:
            continue
        col[std_col] = value
        # amendment provenance: did the winning value come from a 기재정정-patched cell?
        amend_rcepts = [r["amended_by"] for r in cands.get(canon, [])
                        if r["value"] == value and r.get("amended") and r.get("amended_by")]
        if amend_rcepts:
            prov["amended_cols"].append(std_col)
            # dedupe preserving order
            prov["amend_chain"][std_col] = list(dict.fromkeys(amend_rcepts))

    # concept priority override (P1C-1, 2026-08-22 — ported from fin2/standardize/rules.py::
    # rule_map_direct's _COL_PRIORITY, which v3 never received: the loop above only imports
    # DIRECT_MAP, so when a std column has more than one candidate canonical (currently just
    # interest_expense: is.interest_expense vs is.finance_cost), whichever canonical dict
    # iteration happens to process last silently wins the overwrite above — no concept
    # preference. is.finance_cost (금융원가) is a superset that includes interest_expense, so
    # letting it win overstates interest expense whenever a company reports both (confirmed
    # 182 keys via report_lines reproduction, P0.6 T7 — v2 fixed this 2026-07-17(C7), v3 never
    # got the port). Run last so it always overrides the loop above: prefer
    # is.interest_expense, fall back to is.finance_cost only when the former is absent.
    for std_col, priority in _COL_PRIORITY.items():
        for canon in priority:
            if canon in confirmed:
                value = confirmed[canon]
                col[std_col] = value
                # Recompute amendment provenance for the winning canon too — the loop
                # above may have last recorded provenance for the OTHER candidate
                # (e.g. is.finance_cost) before this pass overwrote the value with
                # is.interest_expense's, which would otherwise leave amend_chain
                # attributed to a value that's no longer in col.
                amend_rcepts = [r["amended_by"] for r in cands.get(canon, [])
                                if r["value"] == value and r.get("amended") and r.get("amended_by")]
                if amend_rcepts:
                    if std_col not in prov["amended_cols"]:
                        prov["amended_cols"].append(std_col)
                    prov["amend_chain"][std_col] = list(dict.fromkeys(amend_rcepts))
                else:
                    prov["amend_chain"].pop(std_col, None)
                    if std_col in prov["amended_cols"]:
                        prov["amended_cols"].remove(std_col)
                break

    # is.cogs additive override (2026-08-15, Phase 2 — see _COGS_ADDITIVE_OVERRIDE comment
    # above for the full rationale). Overrides whatever DIRECT_MAP/_resolve() produced for
    # 'cogs' on these curated keys — that value is either a HELD conflict (multi_conflict
    # bucket, so col.get('cogs') is already None/missing here) or a single-subline
    # undercount (multi_needs_sum bucket, wrong but present) — either way the additive sum
    # is the correct figure, verified via the parent-total identity at generation time.
    if merged is not None and (corp, fy, period, basis) in _COGS_ADDITIVE_OVERRIDE:
        want = _COGS_ADDITIVE_OVERRIDE[(corp, fy, period, basis)]
        picked = _cogs_additive_labels(merged, period, basis, want)
        if len(picked) == len(want):
            col["cogs"] = sum(picked.values())

    # industry revenue profile (P1): for insurers etc. whose K-IFRS IS diverges from the
    # general 매출액 standard, standardized revenue = Σ named subtotals, and the components
    # are preserved for the industry-aware tearsheet. Only the build/select path (which has
    # the raw merged lines) applies this; diagnostic (pooled/rcept) paths skip it.
    if merged is not None and rcept_by_stmt is None:
        is_lines = [r for r in merged if r["statement"] == "IS" and r["basis"] == basis]
        if not is_lines and prov["basis_fallback"]:
            other = "separate" if basis == "consolidated" else "consolidated"
            is_lines = [r for r in merged if r["statement"] == "IS" and r["basis"] == other]
        applied = apply_revenue_profile(is_lines, _get_induty(session, corp), corp)
        if applied:
            pname, revenue, components = applied
            col["revenue"] = revenue
            prov["industry_lines"] = {"profile": pname, **components}
    # 증권성 금융지주: 매출액 개념이 없으므로 revenue 는 NULL(사실). DIRECT_MAP 이 수수료수익 등
    # 성분을 revenue 로 오선택했거나 bank 프로파일이 gross 를 억지로 채운 것을 제거. op_income
    # 이하는 그대로 유지(정확 적재됨).
    if corp in NO_REVENUE_CORPS:
        col.pop("revenue", None)
        if prov.get("industry_lines"):
            prov["industry_lines"] = None
    # enrichment (v3-native, 2026-07-25): capex/fcf/net_debt = report_lines-native, reusing
    # the v2 standardize rules against the confirmed canonicals. Additive-only — writes new
    # columns without mutating the existing DIRECT_MAP cols (short_term_debt/long_term_debt
    # included; net_debt uses v3's own debt/cash, additive-enriched as of 2026-08-31 per
    # _V3_ST_DEBT_PARTS/_V3_LT_DEBT_PARTS — see that constant's comment — but that overlay
    # is scoped to net_debt's local computation and never leaks into the persisted columns).
    # D&A·EBITDA are supplied v3-natively from note_lines (2026-07-28) — see _apply_enrichment.
    # shares_out·data_quality still come from separate backfills.
    # ★ note_lines must be read with the *effective* basis: a non-consolidating corp files only
    #   별도, and its notes are stored as basis='separate' even though this row is 'consolidated'.
    #   Ignoring the fallback silently loses D&A for every such corp (실측 미채움의 주원인).
    eff_basis = (("separate" if basis == "consolidated" else "consolidated")
                 if prov["basis_fallback"] else basis)
    _apply_enrichment(session, corp, fy, period, basis, confirmed, col, eff_basis, cands)
    return col, conflicts, prov


def _apply_enrichment(session, corp, fy, period, basis, confirmed, col, note_basis=None,
                      cands=None):
    """Compute capex/fcf/net_debt/D&A/EBITDA in-place on `col` by reusing the v2 standardize
    rules on the confirmed canonicals. Additive: only sets the new keys, never mutates the
    existing DIRECT_MAP cols (short_term_debt/long_term_debt themselves included — see
    _additive_debt_for_net_debt's docstring: its overlay lands on a local ctx.col that this
    function's copy-back loop below never returns). net_debt derives from v3's own short/long
    debt (as of 2026-08-31, additive-enriched per _V3_ST_DEBT_PARTS/_V3_LT_DEBT_PARTS — see
    that constant's comment) + cash. shares_out·data_quality still come from separate backfills.

    D&A (2026-07-28): the body CF has no D&A for many firms, so notes are the real source.
    note_da_canonicals() runs the layer-3 note interpretation chain (topic→period→label) and
    returns note.* canonicals, which feed the *existing* rule_additive_da — no bespoke D&A
    extractor. Notes only supplement: body canonicals win, since rule_additive_da sums the
    canonical families and cf.* is listed ahead of note.*.
    """
    canon = dict(confirmed)
    # 주석 D&A 는 FY + interim 모두 대상(2026-07-29). interim 은 note_da 가 col_label 로
    # '누적' 열을 골라 std_financials 의 누적 기준과 맞춘다 — 누적 열을 못 찾으면 값을 만들지 않는다.
    # 본문에서 이미 D&A 를 확보했으면 주석을 덧대지 않는다(같은 비용 이중 계상 방지).
    if not _has_body_da(canon):
        try:
            rcept = select_canonical_rcept(session, corp, fy, period)
            if rcept:
                canon.update(note_da_canonicals(
                    session, rcept, note_basis or basis, period))
        except Exception:  # noqa: BLE001 — 주석 소스 실패가 표준화 전체를 막으면 안 됨
            pass

    ctx = StdContext(corp_code=corp, fiscal_year=fy, fiscal_period=period,
                     basis=basis, canon=canon, col=dict(col))
    # cash_with_deposits (P1C-2, 2026-08-22) MUST run before rule_derive_net_debt below —
    # v2's own RULES list runs it right after map_direct, ahead of every derived rule, for
    # exactly this reason: net_debt reads ctx.col["cash"], so a financial-company cash figure
    # left un-enriched here (증권/보험 현금+예치금) would flow into a net_debt computed off
    # the pre-enrichment cash value. Additive-only elsewhere: writes col["cash"] only when the
    # 현금및예치금 concept split (bs.cash_deposits_combined/bs.deposits) is actually present.
    rule_cash_with_deposits(ctx)  # cash = 현금성자산 + 예치금 (금융사만, 2026-07-18 규칙, v2 검증됨)
    rule_additive_capex(ctx)     # capex = -(|유형자산취득| + |무형자산취득|)  [cf.capex canonicals]
    rule_derive_fcf(ctx)         # fcf = cfo - |capex|
    # B1-D2 step1 wiring (2026-08-31): overlay ctx.col's short/long debt with the
    # additive sum (_additive_debt_for_net_debt) right before deriving net_debt below.
    # Scoped to this local ctx only — short_term_debt/long_term_debt are not in the
    # copy-back loop at the bottom of this function, so `col` (the persisted std
    # columns) never sees this overlay.
    add_st, add_lt = _additive_debt_for_net_debt(canon, ctx.col)
    if add_st is not None:
        ctx.col["short_term_debt"] = add_st
    if add_lt is not None:
        ctx.col["long_term_debt"] = add_lt
    rule_derive_net_debt(ctx)    # net_debt = (short+long debt) - cash  [v3's own values]
    rule_additive_da(ctx)        # depreciation/amortization/da_total  [cf.* 우선, 없으면 note.*]
    rule_derive_ebitda(ctx)      # ebitda = operating_income + da_total
    for k in ("cash", "capex", "fcf", "net_debt",
              "depreciation", "amortization", "da_total", "ebitda"):
        v = ctx.col.get(k)
        if v is not None:
            col[k] = v


# 본문(CF/IS)에서 이미 D&A 가 잡혔는지 — 잡혔으면 주석을 덧대지 않는다.
_BODY_DA_CANON = ("cf.depreciation", "cf.amortization", "cf.da_total",
                  "cf.rou_depreciation", "is.depreciation", "is.amortization")


def _has_body_da(canon: dict) -> bool:
    return any(canon.get(c) for c in _BODY_DA_CANON)

