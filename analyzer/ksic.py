def sector_key(induty_code: str | None) -> str | None:
    """induty_code → 섹터 키(2자리). None/빈값 → None."""
    if not induty_code:
        return None
    code = str(induty_code).strip()
    return code[:2] if len(code) >= 2 else None


def sector_name(induty_code: str | None) -> str | None:
    """induty_code → 섹터명. 미매핑은 '업종 NN' 폴백."""
    key = sector_key(induty_code)
    if not key:
        return None
    return KSIC_2DIGIT.get(key, f"업종 {key}")
